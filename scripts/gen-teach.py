"""Regenerates src/content/teach/registry.ts from the dayNN.ts files present."""
import pathlib, re
d = pathlib.Path(__file__).resolve().parent.parent / "src/content/teach"
days = sorted(re.match(r"day(\d\d)\.ts", f.name).group(1) for f in d.glob("day*.ts"))
imp = "\n".join(f'import {{ TEACH_{x} }} from "./day{x}";' for x in days)
lst = ", ".join(f"TEACH_{x}" for x in days)
(d / "registry.ts").write_text(f'''/** All full explanations by day. Import through ./index on the server (it adds the server-only guard). Generated by scripts/gen-teach.py. */
import type {{ Teach }} from "./types";
{imp}

export const TEACH: Record<number, Teach> = Object.fromEntries([{lst}].map((t) => [t.day, t]));
''')
print(len(days), "days")
